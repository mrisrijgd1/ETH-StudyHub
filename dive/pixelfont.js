const ROWS = {};
for (const [ch, s] of Object.entries(G)) ROWS[ch] = s.split(' ');

function glyph(c) {
  if (ROWS[c]) return ROWS[c];
  const u = c.toUpperCase();
  if (ROWS[u]) return ROWS[u];
  if (c === 'ß') return ROWS.S;
  return ROWS['?'];
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function measureText(text, scale = 1, spacing = 1) {
  const n = [...String(text)].length;
  return n === 0 ? 0 : (n * (GLYPH_W + spacing) - spacing) * scale;
}

/** Draw `text` with its top-left corner at (x, y). Coordinates are canvas pixels. */
export function drawText(ctx, text, x, y, { scale = 1, color = '#fff', spacing = 1 } = {}) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const c of String(text)) {
    const rows = glyph(c);
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r];
      for (let col = 0; col < GLYPH_W; col++) {
        if (row[col] === '1') ctx.fillRect(cx + col * scale, cy + r * scale, scale, scale);
      }
    }
    cx += (GLYPH_W + spacing) * scale;
  }
}

/** Title-style text with a slight RGB split. */
export function drawSplitText(ctx, text, x, y, { scale = 2, color = '#fffaf0', shadow = '#1b1f3b', split = 1 } = {}) {
  const prev = ctx.globalAlpha;
  ctx.globalAlpha = 0.45;
  drawText(ctx, text, x, y + scale, { scale, color: shadow });
  ctx.globalAlpha = 0.85;
  drawText(ctx, text, x - split, y, { scale, color: '#ff4d6d' });
  drawText(ctx, text, x + split, y, { scale, color: '#38d9e8' });
  ctx.globalAlpha = prev;
  drawText(ctx, text, x, y, { scale, color });
}
