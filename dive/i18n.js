let lang = 'de';
export function setLang(l) { lang = STR[l] ? l : 'de'; }
export function getLang() { return lang; }
export function t(key, vars = {}) {
  const s = (STR[lang] && STR[lang][key]) ?? STR.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ''));
}
